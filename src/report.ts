import { writeFile } from "node:fs/promises";
import { join } from "node:path";
import { estimateCostUsd, formatUsd, priceFromEnv, type PriceConfig } from "./cost.js";
import type { GitSnapshot } from "./git.js";
import { diffSnapshots } from "./git.js";
import type { LedgerEntry, RunState } from "./ledger.js";

export interface ReportSummary {
  runId: string;
  goal: string;
  startedAt: string;
  finishedAt: string | null;
  steps: number;
  filesChanged: string[];
  inputTokens: number;
  outputTokens: number;
  estimatedCostUsd: number;
  approvals: number;
  secretFindings: { pattern: string; line: number; step?: number }[];
  secretScan: "pass" | "fail";
}

export function buildSummary(
  run: RunState,
  entries: LedgerEntry[],
  after: GitSnapshot,
  price: PriceConfig,
): ReportSummary {
  const runEntries = entries.filter((e) => e.runId === run.runId);
  const steps = runEntries.filter((e) => e.kind === "step");
  const inputTokens = steps.reduce((sum, e) => sum + (e.inputTokens ?? 0), 0);
  const outputTokens = steps.reduce((sum, e) => sum + (e.outputTokens ?? 0), 0);
  const secretFindings = runEntries.flatMap((e) =>
    (e.secretFindings ?? []).map((f) => ({ pattern: f.pattern, line: f.line, step: e.step })),
  );
  return {
    runId: run.runId,
    goal: run.goal,
    startedAt: run.startedAt,
    finishedAt: run.finishedAt ?? null,
    steps: steps.length,
    filesChanged: diffSnapshots(run.baseline, after).map((f) => f.path),
    inputTokens,
    outputTokens,
    estimatedCostUsd: estimateCostUsd(inputTokens, outputTokens, price),
    approvals: steps.filter((e) => e.approved).length,
    secretFindings,
    secretScan: secretFindings.length === 0 ? "pass" : "fail",
  };
}

export function renderMarkdown(summary: ReportSummary, entries: LedgerEntry[]): string {
  const runEntries = entries.filter((e) => e.runId === summary.runId);
  const lines: string[] = [
    "# Agent Ledger report",
    "",
    `- **Run:** \`${summary.runId}\``,
    `- **Goal:** ${summary.goal}`,
    `- **Started:** ${summary.startedAt}`,
    `- **Finished:** ${summary.finishedAt ?? "not finished"}`,
    `- **Steps:** ${summary.steps}`,
    `- **Estimated cost:** ${formatUsd(summary.estimatedCostUsd)} (${summary.inputTokens} in / ${summary.outputTokens} out tokens, estimated at ~1 token / 4 chars)`,
    `- **Approvals:** ${summary.approvals} of ${summary.steps} steps`,
    `- **Secret scan:** ${summary.secretScan === "pass" ? "PASS — no secrets found" : `FAIL — ${summary.secretFindings.length} finding(s)`}`,
    "",
    "## Files changed",
    "",
  ];
  if (summary.filesChanged.length === 0) lines.push("(none)");
  for (const file of summary.filesChanged) lines.push(`- \`${file}\``);
  lines.push("", "## Secret findings", "");
  if (summary.secretFindings.length === 0) {
    lines.push("None. No secret patterns were found in recorded inputs or outputs.");
  } else {
    for (const f of summary.secretFindings) {
      lines.push(`- **${f.pattern}** — step ${f.step ?? "?"} , line ${f.line} (secret redacted, never printed)`);
    }
  }
  lines.push("", "## Steps", "");
  for (const e of runEntries.filter((x) => x.kind === "step")) {
    lines.push(
      `### Step ${e.step}: ${e.tool}`,
      "",
      `- Input (sha256 \`${(e.inputHash ?? "").slice(0, 12)}…\`): ${e.inputPreview ?? ""}`,
      `- Output (sha256 \`${(e.outputHash ?? "").slice(0, 12)}…\`): ${e.outputPreview ?? ""}`,
      `- Tokens: ${e.inputTokens ?? 0} in / ${e.outputTokens ?? 0} out — approved: ${e.approved ? "yes" : "no"}`,
      "",
    );
  }
  lines.push(
    "---",
    "",
    "Generated by agent-ledger. Token counts and costs are estimates. " +
      "Verify this report against `.agent-ledger/ledger.jsonl` with `agent-ledger verify`.",
    "",
  );
  return lines.join("\n");
}

export async function writeReport(
  workspace: string,
  summary: ReportSummary,
  entries: LedgerEntry[],
): Promise<{ reportPath: string; summaryPath: string }> {
  const reportPath = join(workspace, "REPORT.md");
  const summaryPath = join(workspace, ".agent-ledger", "summary.json");
  await writeFile(reportPath, renderMarkdown(summary, entries), "utf-8");
  await writeFile(summaryPath, JSON.stringify(summary, null, 2), "utf-8");
  return { reportPath, summaryPath };
}
